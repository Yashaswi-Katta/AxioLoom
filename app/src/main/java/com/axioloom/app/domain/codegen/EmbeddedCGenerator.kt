package com.axioloom.app.domain.codegen

import com.axioloom.app.domain.model.BinaryOperator
import com.axioloom.app.domain.model.MathExpr
import com.axioloom.app.domain.model.SymbolKey
import com.axioloom.app.domain.model.UnaryOperator
import com.axioloom.app.domain.model.references
import java.util.Locale
import kotlin.math.max

enum class CPrecision(val typeName: String, val suffix: String, val mathPrefix: String) {
    FLOAT("float", "f", "f"),
    DOUBLE("double", "", "")
}

data class GeneratedCCode(
    val title: String,
    val headerCode: String,
    val sourceCode: String,
    val arduinoSnippet: String
)

/**
 * 100% Offline Symbolic-to-C99 / Arduino / ESP32 Firmware Code Synthesizer.
 * Generates zero-allocation, ISR-safe C99 functions and real-time Direct-Form IIR filter drivers.
 */
object EmbeddedCGenerator {

    /**
     * Mode A: Generates C99 function from a MathExpr AST with Common Subexpression Elimination.
     */
    fun sanitizeCIdent(name: String): String = name.replace(Regex("[^a-zA-Z0-9_]"), "_")

    fun generateMathFunction(
        expr: MathExpr,
        functionName: String = "evaluate_math",
        precision: CPrecision = CPrecision.FLOAT
    ): GeneratedCCode {
        val type = precision.typeName
        val vars = expr.references().filter { it.kind == SymbolKey.Kind.VALUE }.map { sanitizeCIdent(it.name) }.distinct().sorted()
        val paramList = if (vars.isEmpty()) "void" else vars.joinToString(", ") { "$type $it" }

        // 1. Identify repeated compound subexpressions for Common Subexpression Elimination (CSE)
        val subexprCounts = mutableMapOf<String, Int>()
        collectCompoundSubexprs(expr, subexprCounts, precision)
        val repeatedSubexprs = subexprCounts.filter { it.value > 1 && it.key.length > 3 }.keys

        val cseSubtrees = linkedMapOf<String, String>()
        val rawToTemp = mutableMapOf<String, String>()
        var varCounter = 1

        val exprCode = emitCExpr(expr, precision, cseSubtrees, repeatedSubexprs, rawToTemp) {
            val varName = "tmp_${varCounter++}"
            varName
        }

        val headerBuilder = StringBuilder()
        headerBuilder.appendLine("/**")
        headerBuilder.appendLine(" * Auto-generated by AxioLoom v2.0 (100% Offline Engine)")
        headerBuilder.appendLine(" * Target: Embedded C99 / Arduino / ESP32")
        headerBuilder.appendLine(" */")
        headerBuilder.appendLine("#ifndef ${functionName.uppercase(Locale.US)}_H")
        headerBuilder.appendLine("#define ${functionName.uppercase(Locale.US)}_H")
        headerBuilder.appendLine()
        headerBuilder.appendLine("#include <math.h>")
        headerBuilder.appendLine()
        headerBuilder.appendLine("$type $functionName($paramList);")
        headerBuilder.appendLine()
        headerBuilder.appendLine("#endif /* ${functionName.uppercase(Locale.US)}_H */")

        val srcBuilder = StringBuilder()
        srcBuilder.appendLine("#include \"${functionName}.h\"")
        srcBuilder.appendLine()
        srcBuilder.appendLine("$type $functionName($paramList) {")
        for ((subExpr, tempName) in cseSubtrees) {
            srcBuilder.appendLine("    const $type $tempName = $subExpr;")
        }
        srcBuilder.appendLine("    return $exprCode;")
        srcBuilder.appendLine("}")

        val arduinoBuilder = StringBuilder()
        arduinoBuilder.appendLine("// Arduino Example:")
        arduinoBuilder.appendLine("void setup() {")
        arduinoBuilder.appendLine("    Serial.begin(115200);")
        if (vars.isNotEmpty()) {
            val dummyArgs = vars.joinToString(", ") { "1.0${precision.suffix}" }
            arduinoBuilder.appendLine("    $type res = $functionName($dummyArgs);")
            arduinoBuilder.appendLine("    Serial.println(res);")
        }
        arduinoBuilder.appendLine("}")
        arduinoBuilder.appendLine("void loop() {}")

        return GeneratedCCode(
            title = functionName,
            headerCode = headerBuilder.toString(),
            sourceCode = srcBuilder.toString(),
            arduinoSnippet = arduinoBuilder.toString()
        )
    }

    private fun collectCompoundSubexprs(expr: MathExpr, counts: MutableMap<String, Int>, prec: CPrecision) {
        when (expr) {
            is MathExpr.Number, is MathExpr.Symbol, is MathExpr.Constant, is MathExpr.Otherwise -> return
            is MathExpr.Unary -> {
                collectCompoundSubexprs(expr.value, counts, prec)
                val s = emitRawCExpr(expr, prec)
                counts[s] = (counts[s] ?: 0) + 1
            }
            is MathExpr.Binary -> {
                collectCompoundSubexprs(expr.left, counts, prec)
                collectCompoundSubexprs(expr.right, counts, prec)
                val s = emitRawCExpr(expr, prec)
                counts[s] = (counts[s] ?: 0) + 1
            }
            is MathExpr.Call -> {
                expr.arguments.forEach { collectCompoundSubexprs(it, counts, prec) }
                val s = emitRawCExpr(expr, prec)
                counts[s] = (counts[s] ?: 0) + 1
            }
            is MathExpr.Builtin -> {
                expr.arguments.forEach { collectCompoundSubexprs(it, counts, prec) }
                val s = emitRawCExpr(expr, prec)
                counts[s] = (counts[s] ?: 0) + 1
            }
            is MathExpr.Relational -> {
                collectCompoundSubexprs(expr.left, counts, prec)
                collectCompoundSubexprs(expr.right, counts, prec)
                val s = emitRawCExpr(expr, prec)
                counts[s] = (counts[s] ?: 0) + 1
            }
            else -> {}
        }
    }

    private fun emitRawCExpr(expr: MathExpr, prec: CPrecision): String {
        val dummyCse = linkedMapOf<String, String>()
        val dummyRaw = mutableMapOf<String, String>()
        return emitCExpr(expr, prec, dummyCse, emptySet(), dummyRaw) { "" }
    }

    /**
     * Mode B: Generates ISR-safe real-time digital filter C struct & step function from DiscretizedFilter.
     */
    fun generateFilterDriver(
        filter: DiscretizedFilter,
        filterPrefix: String = "axioloom_filter",
        precision: CPrecision = CPrecision.FLOAT
    ): GeneratedCCode {
        val type = precision.typeName
        val sfx = precision.suffix
        val order = max(filter.bCoeffs.size - 1, filter.aCoeffs.size - 1)
        val macroOrder = "${filterPrefix.uppercase(Locale.US)}_ORDER"

        val headerBuilder = StringBuilder()
        headerBuilder.appendLine("/**")
        headerBuilder.appendLine(" * Auto-generated IIR Digital Filter Driver by AxioLoom v2.0")
        headerBuilder.appendLine(" * Sampling Frequency: ${filter.samplingFreqHz} Hz (Ts = ${filter.samplingPeriodSec} s)")
        headerBuilder.appendLine(" * Difference Equation: ${filter.differenceEquationLatex}")
        headerBuilder.appendLine(" */")
        headerBuilder.appendLine("#ifndef ${filterPrefix.uppercase(Locale.US)}_H")
        headerBuilder.appendLine("#define ${filterPrefix.uppercase(Locale.US)}_H")
        headerBuilder.appendLine()
        headerBuilder.appendLine("#include <stddef.h>")
        headerBuilder.appendLine()
        headerBuilder.appendLine("#define $macroOrder $order")
        headerBuilder.appendLine()
        headerBuilder.appendLine("typedef struct {")
        headerBuilder.appendLine("    $type x_hist[$macroOrder + 1];")
        headerBuilder.appendLine("    $type y_hist[$macroOrder + 1];")
        headerBuilder.appendLine("} ${filterPrefix}_state_t;")
        headerBuilder.appendLine()
        headerBuilder.appendLine("void ${filterPrefix}_init(${filterPrefix}_state_t* state);")
        headerBuilder.appendLine("void ${filterPrefix}_reset(${filterPrefix}_state_t* state);")
        headerBuilder.appendLine("$type ${filterPrefix}_update(${filterPrefix}_state_t* state, $type input_sample);")
        headerBuilder.appendLine()
        headerBuilder.appendLine("#endif /* ${filterPrefix.uppercase(Locale.US)}_H */")

        val srcBuilder = StringBuilder()
        srcBuilder.appendLine("#include \"${filterPrefix}.h\"")
        srcBuilder.appendLine()
        srcBuilder.appendLine("// Filter coefficients:")
        srcBuilder.append("static const $type B_COEFFS[$macroOrder + 1] = {")
        srcBuilder.append(filter.bCoeffs.joinToString(", ") { String.format(Locale.US, "%.7f%s", it, sfx) })
        srcBuilder.appendLine("};")

        srcBuilder.append("static const $type A_COEFFS[$macroOrder + 1] = {")
        srcBuilder.append(filter.aCoeffs.joinToString(", ") { String.format(Locale.US, "%.7f%s", it, sfx) })
        srcBuilder.appendLine("};")
        srcBuilder.appendLine()

        srcBuilder.appendLine("void ${filterPrefix}_init(${filterPrefix}_state_t* state) {")
        srcBuilder.appendLine("    ${filterPrefix}_reset(state);")
        srcBuilder.appendLine("}")
        srcBuilder.appendLine()
        srcBuilder.appendLine("void ${filterPrefix}_reset(${filterPrefix}_state_t* state) {")
        srcBuilder.appendLine("    if (!state) return;")
        srcBuilder.appendLine("    for (size_t i = 0; i <= $macroOrder; i++) {")
        srcBuilder.appendLine("        state->x_hist[i] = 0.0$sfx;")
        srcBuilder.appendLine("        state->y_hist[i] = 0.0$sfx;")
        srcBuilder.appendLine("    }")
        srcBuilder.appendLine("}")
        srcBuilder.appendLine()
        srcBuilder.appendLine("/**")
        srcBuilder.appendLine(" * Direct-Form I Difference Equation Step")
        srcBuilder.appendLine(" * Safe for use inside ESP32 / Arduino timer ISRs.")
        srcBuilder.appendLine(" */")
        srcBuilder.appendLine("$type ${filterPrefix}_update(${filterPrefix}_state_t* state, $type input_sample) {")
        srcBuilder.appendLine("    if (!state) return 0.0$sfx;")
        srcBuilder.appendLine()
        srcBuilder.appendLine("    // Shift input history")
        srcBuilder.appendLine("    for (int i = $macroOrder; i > 0; i--) {")
        srcBuilder.appendLine("        state->x_hist[i] = state->x_hist[i - 1];")
        srcBuilder.appendLine("    }")
        srcBuilder.appendLine("    state->x_hist[0] = input_sample;")
        srcBuilder.appendLine()
        srcBuilder.appendLine("    // Accumulate feedforward terms (b_k * x[n - k])")
        srcBuilder.appendLine("    $type acc = 0.0$sfx;")
        srcBuilder.appendLine("    for (int k = 0; k <= $macroOrder; k++) {")
        srcBuilder.appendLine("        acc += B_COEFFS[k] * state->x_hist[k];")
        srcBuilder.appendLine("    }")
        srcBuilder.appendLine()
        srcBuilder.appendLine("    // Subtract feedback terms (a_k * y[n - k])")
        srcBuilder.appendLine("    for (int k = 1; k <= $macroOrder; k++) {")
        srcBuilder.appendLine("        acc -= A_COEFFS[k] * state->y_hist[k];")
        srcBuilder.appendLine("    }")
        srcBuilder.appendLine()
        srcBuilder.appendLine("    $type y_out = acc / A_COEFFS[0];")
        srcBuilder.appendLine()
        srcBuilder.appendLine("    // Shift output history")
        srcBuilder.appendLine("    for (int i = $macroOrder; i > 0; i--) {")
        srcBuilder.appendLine("        state->y_hist[i] = state->y_hist[i - 1];")
        srcBuilder.appendLine("    }")
        srcBuilder.appendLine("    state->y_hist[0] = y_out;")
        srcBuilder.appendLine()
        srcBuilder.appendLine("    return y_out;")
        srcBuilder.appendLine("}")

        val arduinoBuilder = StringBuilder()
        arduinoBuilder.appendLine("// Arduino / ESP32 Example:")
        arduinoBuilder.appendLine("#include \"${filterPrefix}.h\"")
        arduinoBuilder.appendLine()
        arduinoBuilder.appendLine("static ${filterPrefix}_state_t filterState;")
        arduinoBuilder.appendLine()
        arduinoBuilder.appendLine("void setup() {")
        arduinoBuilder.appendLine("    Serial.begin(115200);")
        arduinoBuilder.appendLine("    ${filterPrefix}_init(&filterState);")
        arduinoBuilder.appendLine("}")
        arduinoBuilder.appendLine()
        arduinoBuilder.appendLine("void loop() {")
        arduinoBuilder.appendLine("    float sensorRaw = analogRead(A0) * (3.3f / 4095.0f);")
        arduinoBuilder.appendLine("    float filtered = ${filterPrefix}_update(&filterState, sensorRaw);")
        arduinoBuilder.appendLine("    Serial.println(filtered);")
        arduinoBuilder.appendLine("    delayMicroseconds(${((1.0 / filter.samplingFreqHz) * 1_000_000).toInt()});")
        arduinoBuilder.appendLine("}")

        return GeneratedCCode(
            title = filterPrefix,
            headerCode = headerBuilder.toString(),
            sourceCode = srcBuilder.toString(),
            arduinoSnippet = arduinoBuilder.toString()
        )
    }

    private fun emitCExpr(
        expr: MathExpr,
        prec: CPrecision,
        cse: MutableMap<String, String>,
        repeated: Set<String>,
        rawToTemp: MutableMap<String, String>,
        allocateTemp: (String) -> String
    ): String {
        if (repeated.isNotEmpty()) {
            val raw = emitRawCExpr(expr, prec)
            if (raw in repeated) {
                rawToTemp[raw]?.let { return it }
                val tempName = allocateTemp(raw)
                rawToTemp[raw] = tempName
                val rendered = emitCExpr(expr, prec, cse, emptySet(), rawToTemp, allocateTemp)
                cse[rendered] = tempName
                return tempName
            }
        }
        val sfx = prec.suffix
        val fn = prec.mathPrefix

        return when (expr) {
            is MathExpr.Number -> "${expr.value}$sfx"
            is MathExpr.Symbol -> sanitizeCIdent(expr.name)
            is MathExpr.Constant -> when (expr) {
                MathExpr.Constant.PI -> "3.14159265358979323846$sfx"
                MathExpr.Constant.E -> "2.71828182845904523536$sfx"
                MathExpr.Constant.INFINITY -> "(1.0$sfx / 0.0$sfx)"
                MathExpr.Constant.I -> "0.0$sfx"
            }
            is MathExpr.Unary -> {
                val inner = emitCExpr(expr.value, prec, cse, repeated, rawToTemp, allocateTemp)
                if (expr.negative) "(-$inner)" else "(+$inner)"
            }
            is MathExpr.Binary -> {
                val l = emitCExpr(expr.left, prec, cse, repeated, rawToTemp, allocateTemp)
                val r = emitCExpr(expr.right, prec, cse, repeated, rawToTemp, allocateTemp)
                when (expr.op) {
                    MathExpr.Op.ADD -> "($l + $r)"
                    MathExpr.Op.SUBTRACT -> "($l - $r)"
                    MathExpr.Op.MULTIPLY -> "($l * $r)"
                    MathExpr.Op.DIVIDE -> "($l / $r)"
                    MathExpr.Op.POWER -> "pow$fn($l, $r)"
                    MathExpr.Op.PARALLEL -> "(($l * $r) / ($l + $r))"
                }
            }
            is MathExpr.Call -> {
                val argList = expr.arguments.map { emitCExpr(it, prec, cse, repeated, rawToTemp, allocateTemp) }
                val inner = argList.firstOrNull() ?: "0.0$sfx"
                when (expr.function.lowercase(Locale.US)) {
                    "sin" -> "sin$fn($inner)"
                    "cos" -> "cos$fn($inner)"
                    "tan" -> "tan$fn($inner)"
                    "asin", "arcsin" -> "asin$fn($inner)"
                    "acos", "arccos" -> "acos$fn($inner)"
                    "atan", "arctan" -> "atan$fn($inner)"
                    "atan2" -> if (argList.size >= 2) "atan2$fn(${argList[0]}, ${argList[1]})" else "atan$fn($inner)"
                    "sinh" -> "sinh$fn($inner)"
                    "cosh" -> "cosh$fn($inner)"
                    "tanh" -> "tanh$fn($inner)"
                    "exp" -> "exp$fn($inner)"
                    "ln", "log" -> "log$fn($inner)"
                    "sqrt" -> "sqrt$fn($inner)"
                    "abs" -> "fabs$fn($inner)"
                    else -> {
                        val sanitizedFn = sanitizeCIdent(expr.function)
                        if (argList.size == 1) "$sanitizedFn$fn($inner)" else "$sanitizedFn(${argList.joinToString(", ")})"
                    }
                }
            }
            is MathExpr.Builtin -> {
                val inner = if (expr.arguments.isNotEmpty()) emitCExpr(expr.arguments[0], prec, cse, repeated, rawToTemp, allocateTemp) else "0.0$sfx"
                when (expr.function) {
                    MathExpr.Function.SIN -> "sin$fn($inner)"
                    MathExpr.Function.COS -> "cos$fn($inner)"
                    MathExpr.Function.TAN -> "tan$fn($inner)"
                    MathExpr.Function.ASIN -> "asin$fn($inner)"
                    MathExpr.Function.ACOS -> "acos$fn($inner)"
                    MathExpr.Function.ATAN -> "atan$fn($inner)"
                    MathExpr.Function.SINH -> "sinh$fn($inner)"
                    MathExpr.Function.COSH -> "cosh$fn($inner)"
                    MathExpr.Function.TANH -> "tanh$fn($inner)"
                    MathExpr.Function.EXP -> "exp$fn($inner)"
                    MathExpr.Function.LOG -> "log$fn($inner)"
                    MathExpr.Function.SQRT -> "sqrt$fn($inner)"
                    MathExpr.Function.ABS -> "fabs$fn($inner)"
                    MathExpr.Function.FACTORIAL -> "tgamma$fn($inner + 1.0$sfx)"
                    MathExpr.Function.UNIT_STEP -> "($inner >= 0.0$sfx ? 1.0$sfx : 0.0$sfx)"
                    MathExpr.Function.RE -> inner
                    MathExpr.Function.IM -> "0.0$sfx"
                    MathExpr.Function.CONJUGATE -> inner
                    else -> "0.0$sfx"
                }
            }
            is MathExpr.Phasor -> {
                val mag = emitCExpr(expr.magnitude, prec, cse, repeated, rawToTemp, allocateTemp)
                val ang = emitCExpr(expr.angleDegrees, prec, cse, repeated, rawToTemp, allocateTemp)
                "($mag * cos$fn($ang * (3.14159265358979323846$sfx / 180.0$sfx)))"
            }
            is MathExpr.Integral,
            is MathExpr.Derivative,
            is MathExpr.Sum,
            is MathExpr.Limit,
            is MathExpr.Matrix,
            is MathExpr.LaplaceTransform,
            is MathExpr.InverseLaplaceTransform,
            is MathExpr.ZTransform,
        is MathExpr.InverseZTransform,
            is MathExpr.Gradient,
            is MathExpr.Divergence,
            is MathExpr.Curl -> "0.0$sfx"
            is MathExpr.TaylorSeries -> emitCExpr(expr.body, prec, cse, repeated, rawToTemp, allocateTemp)
            is MathExpr.Relational -> {
                val l = emitCExpr(expr.left, prec, cse, repeated, rawToTemp, allocateTemp)
                val r = emitCExpr(expr.right, prec, cse, repeated, rawToTemp, allocateTemp)
                "($l ${expr.op.syntax} $r)"
            }
            is MathExpr.Otherwise -> "1"
            is MathExpr.Piecewise -> {
                if (expr.branches.isEmpty()) emitCExpr(expr.defaultExpr, prec, cse, repeated, rawToTemp, allocateTemp)
                else {
                    val defaultStr = emitCExpr(expr.defaultExpr, prec, cse, repeated, rawToTemp, allocateTemp)
                    expr.branches.foldRight(defaultStr) { branch, acc ->
                        val cond = emitCExpr(branch.condition, prec, cse, repeated, rawToTemp, allocateTemp)
                        val valE = emitCExpr(branch.value, prec, cse, repeated, rawToTemp, allocateTemp)
                        "($cond ? $valE : $acc)"
                    }
                }
            }
            is MathExpr.DiscreteSequence -> {
                if (expr.elements.isNotEmpty()) emitCExpr(expr.elements[0], prec, cse, repeated, rawToTemp, allocateTemp) else "0.0$sfx"
            }
            is MathExpr.IndexedSequence -> "${sanitizeCIdent(expr.name)}[((int)(${emitCExpr(expr.index, prec, cse, repeated, rawToTemp, allocateTemp)})) - 1]"
            is MathExpr.DiscreteConvolution,
            is MathExpr.CircularConvolution,
            is MathExpr.DiscreteFourierTransform -> "0.0$sfx"
        }
    }
}
